    @classmethod
    def from_region_json(
        cls,
        region_data: dict,
        area_position: tuple[float, float, float] | None = None
    ) -> 'SplineTubeBoundary':
        """Create SplineTubeBoundary from regions.json data.

        Args:
            region_data: Region dict from regions.json
            area_position: Optional position from resourceareas.json (x, y, z)
                          If provided, spline points will be offset by this position

        Returns:
            SplineTubeBoundary instance
        """
        boundary = region_data.get('boundary', {})
        boundary_size = boundary.get('size', {})

        # Get radius
        radius = float(boundary_size.get('r', 0.0))

        # Get spline control points (LOCAL coordinates from regions.json)
        spline_data = boundary.get('spline', [])
        spline = [
            SplineControlPoint(
                x=float(sp.get('x', 0)),
                y=float(sp.get('y', 0)),
                z=float(sp.get('z', 0)),
                tx=float(sp.get('tx', 0)),
                ty=float(sp.get('ty', 0)),
                tz=float(sp.get('tz', 0)),
                inlength=float(sp.get('inlength', 0)),
                outlength=float(sp.get('outlength', 0)),
            )
            for sp in spline_data
        ]

        # Get position from area_position or region_data
        if area_position:
            pos_x, pos_y, pos_z = area_position
        else:
            pos_x = float(region_data.get('position_x', 0) or 0)
            pos_y = float(region_data.get('position_y', 0) or 0)
            pos_z = float(region_data.get('position_z', 0) or 0)

        instance = cls(
            position_x=pos_x,
            position_y=pos_y,
            position_z=pos_z,
            radius=radius,
            spline=spline,
        )

        # Transform spline to world coordinates
        instance.transform_spline_to_world()

        return instance