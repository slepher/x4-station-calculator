    def get_volume_0x78_14093efc0(self) -> float:
        """Compute tube volume.

        Corresponds to vtable+0x78, function 0x14093efc0.

        Formula:
            Volume = spline_length * π * tube_radius²

        Returns:
            Tube volume
        """
        self._ensure_sampled()

        if self.total_length <= 0 or self.radius <= 0:
            return 0.0

        # π = 0x40490fdb
        pi = 3.14159265358979323846
        return self.total_length * pi * self.radius * self.radius

